<?php
/**
 * Build tool: regenerate src/Data/timezone-countries.php from IANA tzdb sources.
 *
 * Source files (public domain):
 *   https://data.iana.org/time-zones/tzdb/zone1970.tab
 *   https://data.iana.org/time-zones/tzdb/backward
 *
 * This script is CLI-only and never loaded at plugin runtime. It is invoked
 * manually (and from CI) when bumping IANA tzdb to refresh the bundled lookup
 * table. The output table is the only artefact shipped in the plugin ZIP.
 *
 * Usage:
 *   php bin/build-timezone-countries.php /path/to/zone1970.tab /path/to/backward
 *
 * Design choices:
 *   - For multi-country zones (Europe/Berlin lists DE,DK,NO,SE,SJ etc) we keep
 *     the first listed country, which IANA designates as primary. This matches
 *     how every popular tz-to-country library resolves these zones. The small
 *     minority of visitors in a non-primary country may be miscategorised, but
 *     dropping these zones entirely would lose nearly every European visitor.
 *   - `backward` aliases are pre-flattened into the same table so the runtime
 *     lookup is a single hash hit with no alias-resolution layer.
 *   - Generic offset zones (Etc/*, UTC, GMT*) are never present in zone1970.tab
 *     and so are never in the table. The runtime resolver short-circuits them
 *     with a regex anyway.
 *
 * @package Statnive
 */

declare(strict_types=1);

if ( PHP_SAPI !== 'cli' ) {
	fwrite( STDERR, "Error: this script must run from the CLI.\n" );
	exit( 1 );
}

$zone_path     = $argv[1] ?? '';
$backward_path = $argv[2] ?? '';

if ( '' === $zone_path || '' === $backward_path ) {
	fwrite( STDERR, "Usage: php bin/build-timezone-countries.php <zone1970.tab> <backward>\n" );
	exit( 1 );
}
foreach ( [ $zone_path, $backward_path ] as $f ) {
	if ( ! is_readable( $f ) ) {
		fwrite( STDERR, "Cannot read: {$f}\n" );
		exit( 1 );
	}
}

/**
 * Parse zone1970.tab — map each zone to its primary (first-listed) country.
 *
 * @return array<string, string> tz => ISO-3166-1 alpha-2
 */
function parse_zone_file( string $path ): array {
	$out   = [];
	$lines = file( $path, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES );
	foreach ( $lines as $line ) {
		if ( '' === $line || $line[0] === '#' ) {
			continue;
		}
		$parts = preg_split( '/\t+/', $line );
		if ( ! is_array( $parts ) || count( $parts ) < 3 ) {
			continue;
		}
		// Country list is comma-separated; first entry is the IANA-designated primary.
		$primary = strtok( $parts[0], ',' );
		$tz      = $parts[2];
		if ( ! is_string( $primary ) || ! preg_match( '/^[A-Z]{2}$/', $primary ) ) {
			continue;
		}
		$out[ $tz ] = $primary;
	}
	return $out;
}

/**
 * Parse the `backward` link file and return pairs of (alias => target).
 *
 * @return array<string, string>
 */
function parse_backward_file( string $path ): array {
	$out   = [];
	$lines = file( $path, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES );
	foreach ( $lines as $line ) {
		if ( '' === $line || $line[0] === '#' ) {
			continue;
		}
		// Format: "Link\tTARGET\tALIAS" (whitespace flexible).
		$parts = preg_split( '/\s+/', $line );
		if ( ! is_array( $parts ) || count( $parts ) < 3 || $parts[0] !== 'Link' ) {
			continue;
		}
		$target = $parts[1];
		$alias  = $parts[2];
		if ( $alias === '' || $target === '' ) {
			continue;
		}
		$out[ $alias ] = $target;
	}
	return $out;
}

$zones = parse_zone_file( $zone_path );
fwrite( STDERR, sprintf( "Single-country zones from zone1970.tab: %d\n", count( $zones ) ) );

$aliases  = parse_backward_file( $backward_path );
$resolved = 0;
foreach ( $aliases as $alias => $target ) {
	if ( isset( $zones[ $target ] ) && ! isset( $zones[ $alias ] ) ) {
		$zones[ $alias ] = $zones[ $target ];
		++$resolved;
	}
}
fwrite( STDERR, sprintf( "backward aliases resolved: %d\n", $resolved ) );

ksort( $zones, SORT_STRING );

$output_path = __DIR__ . '/../src/Data/timezone-countries.php';
$buf         = "<?php\n\n";
$buf        .= "// phpcs:disable WordPress.Arrays.MultipleStatementAlignment.DoubleArrowNotAligned\n";
$buf        .= "// phpcs:disable Generic.Arrays.DisallowLongArraySyntax.Found\n";
$buf        .= "// Reason: generated lookup table; the variable key widths make column\n";
$buf        .= "// alignment infeasible without a noisy diff on every IANA refresh.\n\n";
$buf        .= "if ( ! defined( 'ABSPATH' ) ) {\n\texit;\n}\n\n";
$buf        .= "/**\n";
$buf        .= " * IANA timezone → ISO 3166-1 alpha-2 country code.\n";
$buf        .= " *\n";
$buf        .= " * Generated by bin/build-timezone-countries.php from public-domain IANA\n";
$buf        .= " * tzdb sources (zone1970.tab + backward). Do not hand-edit — re-run the\n";
$buf        .= " * builder when bumping IANA tzdb.\n";
$buf        .= " *\n";
$buf        .= " * Multi-country zones map to the first-listed (IANA-primary) country.\n";
$buf        .= " * `backward` aliases are pre-flattened to their target's country code.\n";
$buf        .= " *\n";
$buf        .= " * @package Statnive\n";
$buf        .= " *\n";
$buf        .= " * @return array<string, string>\n";
$buf        .= " */\n\n";
$buf        .= "return [\n";
foreach ( $zones as $tz => $code ) {
	$buf .= sprintf( "\t%s => '%s',\n", var_export( $tz, true ), $code );
}
$buf .= "];\n";

if ( false === file_put_contents( $output_path, $buf ) ) {
	fwrite( STDERR, "Failed to write {$output_path}\n" );
	exit( 1 );
}
fwrite( STDERR, sprintf( "Wrote %d entries to %s\n", count( $zones ), $output_path ) );
